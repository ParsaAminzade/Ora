const page = await ctx.newPage();
const ymd = new Date().toISOString().slice(0, 10);
const o = process.env.O || '/tmp/claude-0/ux';
fs.mkdirSync(o, { recursive: true });
await page.goto(`chrome-extension://${id}/index.html?now=${ymd}T12:00:00`);
