import { chromium } from 'playwright';
import fs from 'node:fs'; import path from 'node:path'; import { createHash } from 'node:crypto';
const dist = path.resolve('dist');
const key = JSON.parse(fs.readFileSync('dist/manifest.json')).key;
const id = [...createHash('sha256').update(Buffer.from(key, 'base64')).digest('hex').slice(0, 32)].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('');
const ctx = await chromium.launchPersistentContext(fs.mkdtempSync('/tmp/claude-0/hp-'), { executablePath: '/opt/pw-browsers/chromium', headless: true,
  args: [`--disable-extensions-except=${dist}`, `--load-extension=${dist}`, '--headless=new', '--enable-unsafe-swiftshader', '--use-angle=swiftshader'], viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const ymd = new Date().toISOString().slice(0, 10);
await page.goto(`chrome-extension://${id}/index.html?now=${ymd}T12:00:00`);
await page.waitForTimeout(2000);
await page.getByRole('button', { name: 'شخصی‌سازی' }).click();
await page.getByRole('button', { name: 'کد HTML', exact: true }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'نمونه' }).click();
await page.waitForTimeout(1500);
await page.evaluate(() => { const st = novaStore.getState(); st.setSettings({ background: { ...st.settings.background, kind: 'scene', scene: 'aurora' } }); });
await page.getByLabel('اسم پس‌زمینه').fill('شفق شب');
await page.getByRole('button', { name: 'ذخیره‌ی پس‌زمینه‌ی فعلی' }).click();
await page.evaluate(() => { const st = novaStore.getState(); st.setSettings({ background: { ...st.settings.background, kind: 'color', color: '#1a1420' } }); });
await page.getByRole('button', { name: 'ذخیره‌ی پس‌زمینه‌ی فعلی' }).click();
await page.getByRole('button', { name: /^پس‌زمینه: کد HTML/ }).click();
await page.waitForTimeout(800);
await page.locator('[aria-label="پس‌زمینه‌های من"]').scrollIntoViewIfNeeded();
await page.screenshot({ path: '/tmp/claude-0/html-settings.png', clip: { x: 950, y: 0, width: 490, height: 900 } });
await page.keyboard.press('Escape');
await page.mouse.move(500, 300);
await page.waitForTimeout(3000);
await page.screenshot({ path: '/tmp/claude-0/html-page.png' });
await ctx.close();
